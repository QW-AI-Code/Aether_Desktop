import fs from 'fs'
const r = (p) => fs.readFileSync(p, 'utf8')
const fail = (m) => { console.error('FAIL: ' + m); process.exit(1) }
const cc = r('src/views/customconfigs.js'), ci = r('src/views/cleanip.js')
if (/renderCleanIpCard/.test(cc + ci)) fail('old Clean IP card still present')
if (/cip-card|Clean IP scanner/.test(cc)) fail('old card markup in custom configs')
const par = r('src/styles/parity.css')
if (!/\.view--custom \.ccfg__server \{[^}]*text-overflow: ellipsis/.test(par)) fail('server line must ellipsise')
if (!/\.view--custom \.cc-table-scroll \{ overflow-x: hidden/.test(par)) fail('no horizontal scroll')
const css = r('src/styles/app.css')
if (!/:root\[dir="rtl"\] \.presets__action \{[^}]*direction: rtl/.test(css)) fail('profile buttons RTL in Persian')
const i18n = r('src/i18n.js')
for (const k of ["'Import settings': 'ورود تنظیمات'", "'Export selected profile (non-secret)': 'خروجی پروفایل انتخاب‌شده (غیرمحرمانه)'"]) if (!i18n.includes(k)) fail('missing ' + k)
const wf = r('.github/workflows/build.yml')
if (/core_sync|core_target|github\.event\.inputs/.test(wf)) fail('core sync must not be enabled by inputs')
if (!wf.includes("CORE_SYNC: 'off'")) fail('CORE_SYNC must be off')
if (r('CORE_VERSION').trim() !== '2.4.0') fail('core version')
if (JSON.parse(r('package.json')).version !== '1.4.0') fail('app version')
console.log('PASS: closeout 1.4.0 (card removed, row ellipsis, fa profile buttons, core pinned)')
